router = APIRouter(prefix="/quizzes", tags=["Quizzes"])

@router.post("/generate", response_model=QuizResponse, status_code=status.HTTP_201_CREATED)
def generate_quiz(
    payload: QuizGenerateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Generate a quiz with AI based on selected document or study topic."""
    source_text = ""
    doc_title = payload.topic or "Course Concepts"

    if payload.document_id:
        doc = db.query(Document).filter(Document.id == payload.document_id, Document.user_id == current_user.id).first()
        if not doc:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Document not found.")
        doc_title = doc.filename
        chunks = db.query(DocumentChunk).filter(DocumentChunk.document_id == doc.id).all()
        source_text = "\n\n".join(c.content for c in chunks[:15])

    raw_questions = gemini_service.generate_quiz(
        topic=doc_title,
        text_content=source_text,
        num_questions=payload.num_questions,
        difficulty=payload.difficulty
    )

    quiz = Quiz(
        user_id=current_user.id,
        document_id=payload.document_id,
        title=f"Quiz: {doc_title}",
        difficulty=payload.difficulty
    )
    db.add(quiz)
    db.commit()
    db.refresh(quiz)

    created_questions = []
    for q_data in raw_questions:
        qq = QuizQuestion(
            quiz_id=quiz.id,
            question=q_data["question"],
            options=q_data["options"],
            correct_answer=int(q_data["correct_answer"]),
            explanation=q_data["explanation"]
        )
        db.add(qq)
        created_questions.append(qq)

    db.commit()

    return QuizResponse(
        id=quiz.id,
        user_id=quiz.user_id,
        document_id=quiz.document_id,
        title=quiz.title,
        difficulty=quiz.difficulty,
        created_at=quiz.created_at,
        questions=[QuizQuestionClientResponse.model_validate(q) for q in created_questions]
    )

@router.get("", response_model=List[QuizResponse])
def list_quizzes(
    skip: int = Query(0, ge=0),
    limit: int = Query(50, ge=1, le=100),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """List quizzes generated by the user."""
    quizzes = db.query(Quiz).filter(Quiz.user_id == current_user.id).order_by(Quiz.created_at.desc()).offset(skip).limit(limit).all()
    results = []
    for q in quizzes:
        questions = db.query(QuizQuestion).filter(QuizQuestion.quiz_id == q.id).all()
        results.append(QuizResponse(
            id=q.id,
            user_id=q.user_id,
            document_id=q.document_id,
            title=q.title,
            difficulty=q.difficulty,
            created_at=q.created_at,
            questions=[QuizQuestionClientResponse.model_validate(qu) for qu in questions]
        ))
    return results

@router.get("/{quiz_id}", response_model=QuizResponse)
def get_quiz(
    quiz_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Get quiz questions (without answers) for taking the test."""
    quiz = db.query(Quiz).filter(Quiz.id == quiz_id, Quiz.user_id == current_user.id).first()
    if not quiz:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Quiz not found.")

    questions = db.query(QuizQuestion).filter(QuizQuestion.quiz_id == quiz.id).all()
    return QuizResponse(
        id=quiz.id,
        user_id=quiz.user_id,
        document_id=quiz.document_id,
        title=quiz.title,
        difficulty=quiz.difficulty,
        created_at=quiz.created_at,
        questions=[QuizQuestionClientResponse.model_validate(q) for q in questions]
    )

@router.post("/{quiz_id}/submit", response_model=QuizAttemptResponse)
def submit_quiz(
    quiz_id: str,
    payload: QuizSubmitRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Grade quiz answers on the backend, record the attempt, and reveal score and explanations."""
    quiz = db.query(Quiz).filter(Quiz.id == quiz_id, Quiz.user_id == current_user.id).first()
    if not quiz:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Quiz not found.")

    questions = db.query(QuizQuestion).filter(QuizQuestion.quiz_id == quiz.id).all()
    if not questions:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="This quiz has no questions.")

    score = 0
    graded_results = []
    for q in questions:
        selected_opt = payload.answers.get(q.id)
        is_correct = (selected_opt == q.correct_answer)
        if is_correct:
            score += 1

        graded_results.append(QuestionGradedResult(
            question_id=q.id,
            question=q.question,
            options=q.options,
            selected_option=selected_opt,
            correct_option=q.correct_answer,
            is_correct=is_correct,
            explanation=q.explanation
        ))

    total = len(questions)
    percentage = round((score / total) * 100) if total > 0 else 0

    attempt = QuizAttempt(
        quiz_id=quiz.id,
        user_id=current_user.id,
        score=score,
        total_questions=total,
        answers=payload.answers
    )
    db.add(attempt)
    db.commit()
    db.refresh(attempt)

    return QuizAttemptResponse(
        id=attempt.id,
        quiz_id=attempt.quiz_id,
        user_id=attempt.user_id,
        score=attempt.score,
        total_questions=attempt.total_questions,
        percentage=percentage,
        submitted_at=attempt.submitted_at,
        results=graded_results
    )

@router.get("/{quiz_id}/attempts", response_model=List[QuizAttemptResponse])
def get_quiz_attempts(
    quiz_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """List historical attempts for a quiz."""
    quiz = db.query(Quiz).filter(Quiz.id == quiz_id, Quiz.user_id == current_user.id).first()
    if not quiz:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Quiz not found.")

    attempts = db.query(QuizAttempt).filter(QuizAttempt.quiz_id == quiz.id, QuizAttempt.user_id == current_user.id).order_by(QuizAttempt.submitted_at.desc()).all()

    return [
        QuizAttemptResponse(
            id=a.id,
            quiz_id=a.quiz_id,
            user_id=a.user_id,
            score=a.score,
            total_questions=a.total_questions,
            percentage=round((a.score / a.total_questions) * 100) if a.total_questions > 0 else 0,
            submitted_at=a.submitted_at
        )
        for a in attempts
    ]
