const CATEGORIES = [
  { id: 'general', label: 'General Inquiry' },
  { id: 'documents', label: 'PDF & Indexing' },
  { id: 'chat', label: 'AI Chat & Citations' },
  { id: 'quiz', label: 'Quizzes & Flashcards' },
  { id: 'account', label: 'Account & Security' },
  { id: 'bug', label: 'Report a Problem' },
];

export const HelpSupportScreen = ({ navigation }) => {
  const { user, themeColors, isDark, t } = useApp();
  const styles = useMemo(() => getStyles(themeColors, isDark), [themeColors, isDark]);

  const [expandedFaqId, setExpandedFaqId] = useState('1');
  const [activeTab, setActiveTab] = useState('faq'); // 'faq' | 'contact' | 'history'

  // Contact Form State
  const [subject, setSubject] = useState('');
  const [selectedCategory, setSelectedCategory] = useState('general');
  const [description, setDescription] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [ticketSuccess, setTicketSuccess] = useState('');
  const [ticketError, setTicketError] = useState('');

  // Past Tickets State
  const [tickets, setTickets] = useState([]);
  const [loadingTickets, setLoadingTickets] = useState(false);

  const fetchTickets = async () => {
    setLoadingTickets(true);
    try {
      const data = await api.support.getTickets();
      setTickets(data);
    } catch (err) {
      console.warn('Failed to fetch support tickets:', err);
    } finally {
      setLoadingTickets(false);
    }
  };

  useEffect(() => {
    if (activeTab === 'history') {
      fetchTickets();
    }
  }, [activeTab]);

  const toggleFaq = (id) => {
    setExpandedFaqId(expandedFaqId === id ? null : id);
  };

  const handleSubmitTicket = async () => {
    setTicketError('');
    setTicketSuccess('');

    if (subject.trim().length < 4) {
      setTicketError('Subject must be at least 4 characters long.');
      return;
    }

    if (description.trim().length < 10) {
      setTicketError('Please provide more detail in your description (min 10 characters).');
      return;
    }

    setIsSubmitting(true);
    try {
      await api.support.createTicket({
        subject: subject.trim(),
        category: selectedCategory,
        description: description.trim(),
      });

      setTicketSuccess('Support ticket submitted successfully! Our support engineering team will review it.');
      setSubject('');
      setDescription('');
      setTimeout(() => {
        setTicketSuccess('');
        setActiveTab('history');
      }, 1500);
    } catch (err) {
      setTicketError(err.message || 'Failed to submit support ticket.');
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleBack = () => {
    if (navigation.canGoBack()) {
      navigation.goBack();
    } else {
      navigation.navigate(ROUTES.MAIN_TABS, { screen: ROUTES.TAB_PROFILE });
    }
  };

  return (
    <SafeAreaView style={styles.safeArea}>
      {/* Header */}
      <View style={styles.header}>
        <TouchableOpacity
          onPress={handleBack}
          style={styles.backBtn}
          hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }}
        >
          <Ionicons name="chevron-back" size={24} color={themeColors.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>{t('helpSupport') || 'Help & Support'}</Text>
        <View style={{ width: 24 }} />
      </View>

      <ScrollView contentContainerStyle={styles.container} showsVerticalScrollIndicator={false}>
        {/* Navigation Tabs */}
        <View style={styles.tabsContainer}>
          <TouchableOpacity
            style={[styles.navTab, activeTab === 'faq' && styles.navTabActive]}
            onPress={() => setActiveTab('faq')}
            activeOpacity={0.8}
          >
            <Ionicons
              name="help-circle-outline"
              size={16}
              color={activeTab === 'faq' ? COLORS.primary : themeColors.textSecondary}
              style={{ marginRight: 6 }}
            />
            <Text style={[styles.navTabText, activeTab === 'faq' && styles.navTabTextActive]}>
              Knowledge Base
            </Text>
          </TouchableOpacity>

          <TouchableOpacity
            style={[styles.navTab, activeTab === 'contact' && styles.navTabActive]}
            onPress={() => setActiveTab('contact')}
            activeOpacity={0.8}
          >
            <Ionicons
              name="mail-outline"
              size={16}
              color={activeTab === 'contact' ? COLORS.primary : themeColors.textSecondary}
              style={{ marginRight: 6 }}
            />
            <Text style={[styles.navTabText, activeTab === 'contact' && styles.navTabTextActive]}>
              Contact Team
            </Text>
          </TouchableOpacity>

          <TouchableOpacity
            style={[styles.navTab, activeTab === 'history' && styles.navTabActive]}
            onPress={() => setActiveTab('history')}
            activeOpacity={0.8}
          >
            <Ionicons
              name="receipt-outline"
              size={16}
              color={activeTab === 'history' ? COLORS.primary : themeColors.textSecondary}
              style={{ marginRight: 6 }}
            />
            <Text style={[styles.navTabText, activeTab === 'history' && styles.navTabTextActive]}>
              My Inquiries
            </Text>
          </TouchableOpacity>
        </View>

        {/* TAB 1: FAQ / Knowledge Base */}
        {activeTab === 'faq' && (
          <View>
            <View style={styles.sectionHeaderBox}>
              <Text style={styles.sectionTitle}>Frequently Asked Questions</Text>
              <Text style={styles.sectionSub}>Quick solutions and guides for using StudyMate AI features.</Text>
            </View>

            <View style={styles.faqList}>
              {FAQ_ITEMS.map((item) => {
                const isExpanded = expandedFaqId === item.id;

                return (
                  <View key={item.id} style={[styles.faqCard, SHADOWS.subtle]}>
                    <TouchableOpacity
                      onPress={() => toggleFaq(item.id)}
                      style={styles.faqHeader}
                      activeOpacity={0.8}
                    >
                      <View style={styles.faqTitleCol}>
                        <Text style={styles.faqCategory}>{item.category}</Text>
                        <Text style={styles.faqQuestion}>{item.question}</Text>
                      </View>

                      <Ionicons
                        name={isExpanded ? 'chevron-up' : 'chevron-down'}
                        size={20}
                        color={themeColors.textSecondary}
                      />
                    </TouchableOpacity>

                    {isExpanded && (
                      <View style={styles.faqBody}>
                        <View style={styles.divider} />
                        <Text style={styles.faqAnswer}>{item.answer}</Text>
                      </View>
                    )}
                  </View>
                );
              })}
            </View>
          </View>
        )}

        {/* TAB 2: Contact Support Form */}
        {activeTab === 'contact' && (
          <View>
            <View style={styles.sectionHeaderBox}>
              <Text style={styles.sectionTitle}>Contact Support</Text>
              <Text style={styles.sectionSub}>Have questions or encountered an issue? Our engineering team is here to assist.</Text>
            </View>

            {ticketSuccess ? (
              <View style={styles.successBox}>
                <Ionicons name="checkmark-circle" size={18} color="#059669" style={{ marginRight: 8 }} />
                <Text style={styles.successText}>{ticketSuccess}</Text>
              </View>
            ) : null}

            {ticketError ? (
              <View style={styles.errorBox}>
                <Ionicons name="alert-circle" size={18} color="#DC2626" style={{ marginRight: 8 }} />
                <Text style={styles.errorText}>{ticketError}</Text>
              </View>
            ) : null}

            <View style={[styles.formCard, SHADOWS.subtle]}>
              <Text style={styles.fieldLabel}>Topic Category</Text>
              <View style={styles.categoryPillsRow}>
                {CATEGORIES.map((cat) => {
                  const isCatSelected = selectedCategory === cat.id;
                  return (
                    <TouchableOpacity
                      key={cat.id}
                      onPress={() => setSelectedCategory(cat.id)}
                      style={[styles.categoryPill, isCatSelected && styles.categoryPillActive]}
                      activeOpacity={0.7}
                    >
                      <Text
                        style={[
                          styles.categoryPillText,
                          isCatSelected && styles.categoryPillTextActive,
                        ]}
                      >
                        {cat.label}
                      </Text>
                    </TouchableOpacity>
                  );
                })}
              </View>

              <Text style={styles.fieldLabel}>Subject</Text>
              <TextInput
                value={subject}
                onChangeText={setSubject}
                placeholder="Brief summary of your question"
                placeholderTextColor={themeColors.textMuted}
                style={styles.textInput}
              />

              <Text style={styles.fieldLabel}>Detailed Description</Text>
              <TextInput
                value={description}
                onChangeText={setDescription}
                placeholder="Explain the issue in detail, including steps to reproduce..."
                placeholderTextColor={themeColors.textMuted}
                multiline
                numberOfLines={4}
                style={[styles.textInput, styles.textArea]}
              />

              <PrimaryButton
                title={isSubmitting ? 'Submitting...' : 'Submit Support Ticket'}
                onPress={handleSubmitTicket}
                loading={isSubmitting}
                style={{ marginTop: 8 }}
              />
            </View>
          </View>
        )}

        {/* TAB 3: Ticket History */}
        {activeTab === 'history' && (
          <View>
            <View style={styles.sectionHeaderBox}>
              <Text style={styles.sectionTitle}>Support Inquiries</Text>
              <Text style={styles.sectionSub}>Track status and responses to your submitted tickets.</Text>
            </View>

            {loadingTickets ? (
              <ActivityIndicator size="large" color={COLORS.primary} style={{ marginTop: 40 }} />
            ) : tickets.length === 0 ? (
              <View style={[styles.emptyBox, SHADOWS.subtle]}>
                <Ionicons name="chatbubbles-outline" size={48} color={themeColors.textMuted} />
                <Text style={styles.emptyTitle}>No Inquiries Yet</Text>
                <Text style={styles.emptySub}>
                  You haven't submitted any support requests. Switch to the 'Contact Team' tab to get assistance.
                </Text>
              </View>
            ) : (
              tickets.map((tItem) => (
                <View key={tItem.id} style={[styles.ticketCard, SHADOWS.subtle]}>
                  <View style={styles.ticketHeader}>
                    <Text style={styles.ticketCategory}>
                      {CATEGORIES.find((c) => c.id === tItem.category)?.label || tItem.category}
                    </Text>
                    <View style={styles.statusBadge}>
                      <Text style={styles.statusText}>{tItem.status.toUpperCase()}</Text>
                    </View>
                  </View>
                  <Text style={styles.ticketSubject}>{tItem.subject}</Text>
                  <Text style={styles.ticketDesc}>{tItem.description}</Text>
                  <Text style={styles.ticketDate}>
                    {new Date(tItem.created_at).toLocaleDateString()} at{' '}
                    {new Date(tItem.created_at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                  </Text>
                </View>
              ))
            )}
          </View>
        )}
      </ScrollView>
    </SafeAreaView>
  );
};

